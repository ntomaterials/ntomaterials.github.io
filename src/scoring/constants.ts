/**
 * Константы методики расчёта 
 *
 * Это параметры методологии, а не данных: они одинаковы при любой замене CSV.
 * Размерности (число кластеров, профилей, вопросов) сюда не входят — они
 * определяются из CSV и живут в Dataset.
 */

/**
 * Баллы, начисляемые за варианты ответа (единственное место в проекте,
 * где это настраивается). Колонки банка вопросов (positive_3, positive_2,
 * neutral_1, negative_0 в build/data-loader.ts) сопоставляются с этими
 * значениями по смыслу варианта, а не по числу в названии колонки.
 * Значения могут быть как целыми, так и дробными.
 */
export const POSITIVE_MAX = 3;
export const POSITIVE = 2;
export const NEUTRAL = 0.25;
export const NEGATIVE = 0;

/**
 * Верхняя граница шкалы весов матрицы, ответов и вектора пользователя.
 * Веса матрицы — целые {0 .. POSITIVE_MAX}; ответы уже даны в той же шкале,
 * поэтому дополнительная нормализация ответов не нужна.
 * Отсюда же диапазон расстояния D ∈ [0 .. SCALE_MAX].
 */
export const SCALE_MAX = POSITIVE_MAX;

/** Сколько профилей показываем в результате. */
export const TOP_N = 3;

/** Сколько опорных тем показываем в блоке «почему подходит». */
export const TOP_STRENGTHS = 2;

/**
 * Порог надёжности для евклидовой методики: если D[2-е место] − D[1-е место]
 * меньше порога, показываем предупреждение о близких результатах.
 * 0.30 ≈ 10% от максимального расстояния 3.0.
 */
export const EUCLIDEAN_GAP_THRESHOLD = 0.3;

/** Порог надёжности для методики средневзвешенного балла (разрыв по SCORE). */
export const WEIGHTED_AVERAGE_GAP_THRESHOLD = 0.1;

/** Ниже этого процента совпадения считаем, что предпочтения не выражены. */
export const LOW_ENGAGEMENT_PERCENT = 45;

/** Вес компоненты, начиная с которого профиль «требует» эту тему. */
export const CAUTION_WEIGHT_THRESHOLD = 2;

/**
 * Нормализованный балл участника (0..1) ниже этого значения по «требуемой»
 * теме — повод показать предупреждение по профилю.
 */
export const CAUTION_SCORE_THRESHOLD = 0.35;

/** Вес предметной оси S_A в методике средневзвешенного балла. */
export const WEIGHT_AXIS_A = 4;

/** Вес деятельностной оси S_B в методике средневзвешенного балла. */
export const WEIGHT_AXIS_B = 2;
